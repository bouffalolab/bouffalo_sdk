#!/usr/bin/env python3
"""Generate SDK Code Bitmap fonts from the pinned Monaspace Neon Regular source.

Requires Pillow (host generation only). Firmware uses the generated constant arrays.
SPDX-License-Identifier: Apache-2.0
"""
import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from urllib.request import urlopen

from PIL import Image, ImageDraw, ImageFont, __version__ as PILLOW_VERSION
from PIL import features

COMMIT = "f31794b6e9e65698a062262e2f826f679dcb7070"
SOURCE_URL = (f"https://raw.githubusercontent.com/githubnext/monaspace/{COMMIT}/"
              "fonts/Static%20Fonts/Monaspace%20Neon/MonaspaceNeon-Regular.otf")
SOURCE_SHA256 = "0daf2cd6cbd780b1a9426cb25c17e80f22844051f988a5133ad54b2751b0b8af"
FONTS = (("ascii_16x8", 8, 16, 32, 95),
         ("ascii_32x16", 16, 32, 32, 95),
         ("ascii_64x32", 32, 64, 48, 10))
SCALE = 4
THRESHOLD = 96


def rasterize(source, width, height, first, count):
    """Uniform aspect ratio and common ASCII baseline; no per-glyph stretching."""
    # Fit the union of ALL printable ASCII at every size, including the digits-only
    # font. This keeps baseline/scale consistent, not normalized to individual glyphs.
    probe = ImageFont.truetype(BytesIO(source), 1000, layout_engine=ImageFont.Layout.BASIC)
    bounds = [probe.getbbox(chr(c), anchor="ls") for c in range(32, 127)]
    extent = max(b[3] for b in bounds) - min(b[1] for b in bounds)
    advance = probe.getlength("M")
    size = int(min((width - 1) * SCALE * 1000 / advance,
                   (height - 2) * SCALE * 1000 / extent))
    font = ImageFont.truetype(BytesIO(source), size, layout_engine=ImageFont.Layout.BASIC)
    boxes = [font.getbbox(chr(c), anchor="ls") for c in range(32, 127)]
    top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
    x = round((width * SCALE - font.getlength("M")) / 2)
    baseline = (height * SCALE - (bottom - top)) // 2 - top
    glyphs = []
    images = []
    for code in range(first, first + count):
        high = Image.new("L", (width * SCALE, height * SCALE))
        ImageDraw.Draw(high).text((x, baseline), chr(code), font=font, fill=255, anchor="ls")
        low = high.resize((width, height), Image.Resampling.LANCZOS)
        binary = low.point(lambda v: 255 if v >= THRESHOLD else 0, mode="1")
        if code != 32 and not binary.getbbox():
            raise ValueError(f"Empty glyph {code:#x} at {width}x{height}")
        glyphs.append(binary.tobytes())
        images.append(binary)
    return glyphs, images


def render_source(name, width, height, first, glyphs):
    length = height * ((width + 7) // 8)
    assert all(len(g) == length for g in glyphs)
    digest = sha256(b"".join(glyphs)).hexdigest()
    lines = ["/**", f" * @brief SDK Code Bitmap: width {width}, height {height}, 1bpp ASCII.",
             " * Derived from Monaspace Neon Regular v1.400; copyright (c) 2023 GitHub.",
             " * Generated by tools/generate_fonts.py; do not hand-edit bitmap data.",
             f" * Source SHA256: {SOURCE_SHA256}",
             f" * Bitmap SHA256: {digest}",
             f" * Generator: Pillow {PILLOW_VERSION}, FreeType {features.version_module('freetype2')};",
             f" * 4x supersampling, Lanczos downsample, threshold {THRESHOLD}/255, shared ASCII baseline.",
             " * Font data: SPDX-License-Identifier: OFL-1.1 (see tools/LICENSE.OFL).", " */",
             '#include "simple_font/display_simple_font.h"', "",
             "/* One character per entry; row-major bytes, MSB leftmost. */",
             f"static const uint8_t bitmap[{len(glyphs)}][{length}] = {{"]
    for code, glyph in enumerate(glyphs, first):
        label = "space" if code == 32 else chr(code)
        lines.append(f"    {{ /* 0x{code:02X}: {label} */")
        for i in range(0, length, 16):
            lines.append("        " + ", ".join(f"0x{v:02X}" for v in glyph[i:i + 16]) + ",")
        lines.append("    },")
    lines += ["};", "", f"const display_simple_font_t display_simple_font_{name} = {{",
              f"    .width = {width},", f"    .height = {height},", f"    .first_char = 0x{first:02X},",
              f"    .char_count = {len(glyphs)},", "    .bitmap = &bitmap[0][0],", "};", ""]
    return "\n".join(lines)


def preview_image(all_images, target):
    sheet = Image.new("RGB", (960, 440), "#18202b")
    draw = ImageDraw.Draw(sheet)
    for row, ((name, width, height, first, _), images) in enumerate(zip(FONTS, all_images)):
        y = row * 140
        draw.text((10, y + 4), f"SDK Code Bitmap {width} x {height}", fill="white")
        text = "0O1Il| {}[]() <> != +-*/ _.,:;" if row != 2 else "0123456789"
        for i, ch in enumerate(text):
            glyph = images[ord(ch) - first].convert("L")
            if row == 0:
                glyph = glyph.resize((width * 3, height * 3), Image.Resampling.NEAREST)
            elif row == 1:
                glyph = glyph.resize((width * 2, height * 2), Image.Resampling.NEAREST)
            sheet.paste("#e8eef6", (10 + i * (glyph.width + 4), y + 26), glyph)
    sheet.save(target)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, help="Local pinned OTF; otherwise download the official file")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--preview", type=Path, help="Optional PNG comparison sheet")
    parser.add_argument("--check", action="store_true", help="Compare generated C with files without writing them")
    args = parser.parse_args()
    if args.font:
        source = args.font.read_bytes()
    else:
        with urlopen(SOURCE_URL, timeout=60) as response:
            source = response.read()
    if sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("Source font SHA256 mismatch; expected pinned Monaspace Neon Regular v1.400")
    all_images = []
    for name, width, height, first, count in FONTS:
        glyphs, images = rasterize(source, width, height, first, count)
        all_images.append(images)
        path = args.output / f"display_simple_font_{name}.c"
        content = render_source(name, width, height, first, glyphs)
        if args.check:
            if path.read_text() != content:
                raise ValueError(f"Generated font differs: {path}")
        else:
            path.write_text(content)
        print(f"{'Checked' if args.check else 'Generated'} {path.name}: {width}x{height}, {count} glyphs")
    if args.preview:
        preview_image(all_images, args.preview)


if __name__ == "__main__":
    main()
