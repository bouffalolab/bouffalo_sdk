/* Display on and tearing effect on, in the vendor order (the driver sends display on again at enable) */
static const display_dcs_cmd_t st7701p_display_on[] = {
    DISPLAY_DCS0(0x29, 0),
    DISPLAY_DCS(0x35, 0, 0x00), /* Tearing Effect On */
};

/* Command port of the RGB panel: 3-wire 9-bit or 4-wire SPI */
static const display_link_t st7701p_links[] = {
    { .iface = DISPLAY_IFACE_DBI_C3 },
    { .iface = DISPLAY_IFACE_DBI_C4 },
};

/* The RAM size is the size of the panel: the RGB interface does not use the GRAM windows */
const display_dcs_ic_t display_ic_st7701p = {
    .name = "st7701p",
    .ram_width = 480,
    .ram_height = 480,
    .reset_low_ms = 10,
    .reset_wait_ms = 100,
    DISPLAY_DCS_LINKS(st7701p_links),
    DISPLAY_DCS_INIT(st7701p_init),
};

