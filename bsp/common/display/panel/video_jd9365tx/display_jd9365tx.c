/*
 * 240 MHz / 4 = 60 MHz: 800 x 1510 clocks per frame give about 49.7 Hz. RGB888 over 2 lanes needs 720 Mbit/s per
 * lane, so 850 Mbit/s is used. The panel has an external, fixed reset circuit: a board without a reset line
 * must give the panel its power-up time before the first command.
 */
static const display_video_mode_t video_720x1280[] = {
    {
        .link = DISPLAY_VLINK_DSI,
        .width = 720,
        .height = 1280,
        .hsw = 20,
        .hbp = 40,
        .hfp = 20,
        .vsw = 2,
        .vbp = 28,
        .vfp = 200,
        .clock_hz = 60000000,
        .dsi = { .lanes = 2, .lane_mbps = 850, .format = DISPLAY_DSI_FMT_RGB888 },
    },
};

const display_dcs_module_t display_module_jd9365tx_720x1280 = {
    .name = "jd9365tx_720x1280",
    .ic = &display_ic_jd9365tx,
    .width = 720,
    .height = 1280,
    .video_start_delay_ms = 50, /* the display is on, the panel needs this time before the first line */
    DISPLAY_DCS_VIDEO(video_720x1280),
};
