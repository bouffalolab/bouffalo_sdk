/*
 * 160 MHz / 7 = 22.86 MHz: 378 x 1195 clocks per frame give about 50.6 Hz (the vendor script asks for 28 MHz,
 * which the display clock cannot produce). RGB565 over one lane needs about 366 Mbit/s, so 400 Mbit/s is
 * enough.
 */
