static void jd9365tx_7kf82_backlight_enable(void)
{
    struct bflb_device_s *gpio = bflb_device_get_by_name("gpio");

    if (gpio != NULL) {
        bflb_gpio_init(gpio, JD9365TX_7KF82_BACKLIGHT_PIN,
                       GPIO_OUTPUT | GPIO_PULLUP | GPIO_SMT_EN | GPIO_DRV_0);
        bflb_gpio_set(gpio, JD9365TX_7KF82_BACKLIGHT_PIN);
    }
}

static void jd9365tx_7kf82_run_init_table(void)
{
    for (uint32_t i = 0; i < sizeof(jd9365tx_7kf82_init) / sizeof(jd9365tx_7kf82_init[0]); i++) {
        const struct jd9365tx_7kf82_init_cmd *init_cmd = &jd9365tx_7kf82_init[i];
        uint8_t data_type = DSI_V2_GENERIC_LONG_WRITE;

        if (init_cmd->cmd == DSI_V2_DCS_SET_TEAR_ON ||
            init_cmd->cmd == DSI_V2_DCS_EXIT_SLEEP_MODE ||
            init_cmd->cmd == DSI_V2_DCS_SET_DISPLAY_ON) {
            data_type = 0;
        }

        mipi_dsi_v2_dcs_write_cmd(data_type, init_cmd->cmd,
                                   init_cmd->len ? init_cmd->payload : NULL, init_cmd->len);
        if (init_cmd->delay_ms != 0) {
            bflb_mtimer_delay_ms(init_cmd->delay_ms);
        }
    }
}

static int jd9365tx_7kf82_prepare(void)
{
    mipi_dsi_v2_setup(&jd9365tx_7kf82_timing);

    /* Reset is an external fixed circuit. Match the validated reference's
     * controller-settle and panel-power delays before LPDT initialization. */
    bflb_mtimer_delay_ms(20);
    jd9365tx_7kf82_backlight_enable();
    bflb_mtimer_delay_ms(120);

    jd9365tx_7kf82_run_init_table();
    mipi_dsi_v2_hs_mode_start(&jd9365tx_7kf82_timing);
    return 0;
}

int jd9365tx_7kf82_dsi_init(jd9365tx_7kf82_dsi_color_t *screen_buffer)
{

#if (JD9365TX_7KF82_OSD0_FORMAT != MIPI_DSI_V2_OSD_FORMAT_NONE) || \
    (JD9365TX_7KF82_FB_MODE == JD9365TX_7KF82_FB_MODE_RGB565)
    if (screen_buffer == NULL) {
        return -1;
    }
#endif

    int ret = jd9365tx_7kf82_prepare();
    if (ret != 0) {
        return ret;
    }

    const mipi_dsi_v2_init_t init_config = {
        .timing = &jd9365tx_7kf82_timing,
        .base_frame_buff = (JD9365TX_7KF82_OSD0_FORMAT == MIPI_DSI_V2_OSD_FORMAT_NONE &&
                            JD9365TX_7KF82_FB_MODE == JD9365TX_7KF82_FB_MODE_RGB565) ? screen_buffer : NULL,
        .osd0_frame_buff = (JD9365TX_7KF82_OSD0_FORMAT != MIPI_DSI_V2_OSD_FORMAT_NONE) ? screen_buffer : NULL,
        .base_format = (JD9365TX_7KF82_FB_MODE == JD9365TX_7KF82_FB_MODE_RGB565) ? DPI_DATA_FORMAT_RGB565 : DPI_DATA_FORMAT_Y_UV_PLANAR,
        .osd_format = JD9365TX_7KF82_OSD0_FORMAT,
    };
    return mipi_dsi_v2_display_init(&init_config);
}

