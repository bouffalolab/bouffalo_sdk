static int audio_codec_acm8852_set_sample_rate(audio_codec_dev_t *dev, uint32_t sample_rate_hz)
{
    audio_codec_cfg_t cfg;
    uint8_t i2s_data_format1;
    uint8_t i2s_data_format1_mask;

    if (dev == NULL || dev->i2c == NULL) {
        return -1;
    }
    if (!acm8852_is_supported_sample_rate(sample_rate_hz)) {
        return -2;
    }

    if (dev->priv != NULL) {
        cfg = *(audio_codec_cfg_t *)dev->priv;
    } else {
        cfg.sample_rate_hz = sample_rate_hz;
        cfg.channels = 2;
        cfg.i2s_fmt = AUDIO_CODEC_I2S_FMT_I2S;
        cfg.bits = AUDIO_CODEC_BITS_24;
        cfg.codec_master = false;
        cfg.enable_adc = false;
        cfg.enable_dac = true;
        cfg.work_mode = AUDIO_CODEC_WORK_MODE_PLAYBACK;
        cfg.mic_input_mode = AUDIO_CODEC_MIC_INPUT_DIFF;
    }

    cfg.sample_rate_hz = sample_rate_hz;
    if (acm8852_get_i2s_data_format(&cfg, &i2s_data_format1, &i2s_data_format1_mask) != 0) {
        return -2;
    }
    if (acm8852_config_i2s(dev, i2s_data_format1, i2s_data_format1_mask) != 0) {
        return -1;
    }

    g_acm8852_cfg = cfg;
    dev->priv = &g_acm8852_cfg;
    return 0;
}

static uint32_t audio_codec_acm8852_calc_mclk_hz(uint32_t sample_rate_hz)
{
    return sample_rate_hz * 256U;
}

int audio_codec_acm8852_read_register(struct bflb_device_s *i2c, uint8_t addr, uint8_t page, uint8_t reg, uint8_t *val)
{
    if (i2c == NULL || val == NULL) {
        return -1;
    }

    if (acm8852_select_page(i2c, addr, page) != 0) {
        return -1;
    }

    return acm8852_read_reg(i2c, addr, reg, val);
}

int audio_codec_acm8852_write_register(struct bflb_device_s *i2c, uint8_t addr, uint8_t page, uint8_t reg, uint8_t val)
{
    if (i2c == NULL) {
        return -1;
    }

    if (acm8852_select_page(i2c, addr, page) != 0) {
        return -1;
    }

    return acm8852_write_reg(i2c, addr, reg, val);
}

