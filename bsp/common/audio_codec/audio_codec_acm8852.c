{
    return audio_codec_i2c_read_reg8(i2c, addr, reg, val);
}

static int acm8852_select_page(struct bflb_device_s *i2c, uint8_t addr, uint8_t page)
{
    return acm8852_write_reg(i2c, addr, ACM8852_REG_PAGE_SELECT, page);
}

static int acm8852_update_bits(struct bflb_device_s *i2c, uint8_t addr, uint8_t reg, uint8_t mask, uint8_t val)
{
    uint8_t old_val = 0;
    uint8_t new_val;

    if (acm8852_read_reg(i2c, addr, reg, &old_val) != 0) {
        return -1;
    }

    new_val = (uint8_t)((old_val & (uint8_t)(~mask)) | (val & mask));
    if (new_val == old_val) {
        return 0;
    }

    return acm8852_write_reg(i2c, addr, reg, new_val);
}

static uint8_t acm8852_map_bits(audio_codec_bits_t bits)
{
    switch (bits) {
        case AUDIO_CODEC_BITS_16:
            return 0x00;
        case AUDIO_CODEC_BITS_32:
            return 0x03;
        case AUDIO_CODEC_BITS_24:
        default:
            return 0x02;
    }
}

static int acm8852_map_fmt(audio_codec_i2s_fmt_t fmt, uint8_t *fmt_bits, uint8_t *lrck_pulse_bits)
{
    if (fmt_bits == NULL || lrck_pulse_bits == NULL) {
        return -1;
    }

    *lrck_pulse_bits = 0x00;
    switch (fmt) {
        case AUDIO_CODEC_I2S_FMT_I2S:
            *fmt_bits = 0x00;
            return 0;
        case AUDIO_CODEC_I2S_FMT_DSP:
            *fmt_bits = 0x01;
            *lrck_pulse_bits = 0x01;
            return 0;
        case AUDIO_CODEC_I2S_FMT_LEFT_J:
            *fmt_bits = 0x02;
            return 0;
        case AUDIO_CODEC_I2S_FMT_RIGHT_J:
            *fmt_bits = 0x03;
            return 0;
        default:
            return -1;
    }
}

static bool acm8852_is_supported_sample_rate(uint32_t sample_rate_hz)
{
    switch (sample_rate_hz) {
        case 32000U:
        case 44100U:
        case 48000U:
        case 88200U:
        case 96000U:
        case 176400U:
        case 192000U:
            return true;
        default:
            return false;
    }
}

static int acm8852_get_i2s_data_format(const audio_codec_cfg_t *cfg, uint8_t *data_format1,
                                       uint8_t *data_format1_mask)
{
    uint8_t fmt_bits = 0;
    uint8_t lrck_pulse_bits = 0;

    if (cfg == NULL || data_format1 == NULL || data_format1_mask == NULL ||
        cfg->channels == 0U || cfg->channels > 2U) {
        return -2;
    }
    if (acm8852_map_fmt(cfg->i2s_fmt, &fmt_bits, &lrck_pulse_bits) != 0) {
        return -2;
    }

    *data_format1 = (uint8_t)((fmt_bits << 4) | (lrck_pulse_bits << 2) | acm8852_map_bits(cfg->bits));
    *data_format1_mask = 0x33;

    if (cfg->i2s_fmt == AUDIO_CODEC_I2S_FMT_DSP) {
        *data_format1_mask |= 0x0c;
    }
    if (cfg->sample_rate_hz == 44100U) {
        *data_format1 |= 0xc0;
        *data_format1_mask |= 0xc0;
    }

    return 0;
}

static int acm8852_config_i2s(audio_codec_dev_t *dev, uint8_t data_format1, uint8_t data_format1_mask)
{
    int ret = 0;

    ret |= acm8852_select_page(dev->i2c, dev->i2c_addr, 0x00);
    ret |= acm8852_update_bits(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_I2S_DATA_FORMAT1,
                               data_format1_mask, data_format1);
    ret |= acm8852_write_reg(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_I2S_DATA_FORMAT2, 0x00);
    ret |= acm8852_write_reg(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_I2S_DATA_FORMAT3, 0x00);
    ret |= acm8852_update_bits(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_I2S_BAK2, 0x30, 0x00);

    return (ret == 0) ? 0 : -1;
}

static int acm8852_set_output_state(audio_codec_dev_t *dev, uint8_t state, bool mute)
{
    uint8_t val = (uint8_t)(state & ACM8852_STATE_MASK);
    int ret = 0;

    if (mute) {
        val |= ACM8852_MUTE_MASK;
    }

    ret |= acm8852_select_page(dev->i2c, dev->i2c_addr, 0x00);
    ret |= acm8852_update_bits(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_STATE_CTRL2,
                               ACM8852_STATE_MASK | ACM8852_MUTE_MASK, val);
    ret |= acm8852_update_bits(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_STATE_CTRL3,
                               ACM8852_STATE_MASK | ACM8852_MUTE_MASK, val);
    return (ret == 0) ? 0 : -1;
}

static int acm8852_write_init_sequence(audio_codec_dev_t *dev)
{
    for (size_t i = 0; i < (sizeof(acm8852_init_regs) / sizeof(acm8852_init_regs[0])); i++) {
        if (acm8852_write_reg(dev->i2c, dev->i2c_addr, acm8852_init_regs[i].reg, acm8852_init_regs[i].val) != 0) {
            return -1;
        }

        if (i == ACM8852_INIT_HIZ_INDEX) {
            bflb_mtimer_delay_ms(10);
        }
    }

    return 0;
}

static void acm8852_read_all_regs(audio_codec_dev_t *dev)
{
    uint8_t val;

    if (dev == NULL || dev->i2c == NULL) {
        return;
    }

    printf("ACM8852 register dump, i2c addr 0x%02x\r\n", dev->i2c_addr);
    for (uint8_t page = 0x00; page <= 0x0d; page++) {
        if (acm8852_select_page(dev->i2c, dev->i2c_addr, page) != 0) {
            printf("ACM8852 page 0x%02x select failed\r\n", page);
            continue;
        }

        printf("ACM8852 page 0x%02x\r\n", page);
        for (uint16_t reg = 0; reg < 0x100; reg++) {
            if (acm8852_read_reg(dev->i2c, dev->i2c_addr, (uint8_t)reg, &val) == 0) {
                printf("0x%02x 0x%02x\r\n", (unsigned int)reg, val);
            } else {
                printf("0x%02x XX\r\n", (unsigned int)reg);
            }
        }
    }
}

static int audio_codec_acm8852_probe(struct bflb_device_s *i2c, uint8_t addr)
{
    uint8_t die_id = 0;

    if (i2c == NULL) {
        return -1;
    }

    if (acm8852_select_page(i2c, addr, 0x00) != 0) {
        return -1;
    }
    if (acm8852_read_reg(i2c, addr, ACM8852_REG_DIG_DIEID_RPT, &die_id) != 0) {
        return -1;
    }

    return (die_id == ACM8852_DIE_ID_VALUE) ? 0 : -1;
}

static int audio_codec_acm8852_init(audio_codec_dev_t *dev, const audio_codec_cfg_t *cfg)
{
    bool try_all_i2c_addrs;
    uint8_t i2s_data_format1;
    uint8_t i2s_data_format1_mask;
    int ret;

    if (dev == NULL || dev->i2c == NULL || cfg == NULL) {
        return -1;
    }
    try_all_i2c_addrs = (dev->i2c_addr == 0U);

    if (cfg->codec_master || cfg->enable_adc || cfg->work_mode == AUDIO_CODEC_WORK_MODE_RECORDING) {
        return -2;
    }
    if (!acm8852_is_supported_sample_rate(cfg->sample_rate_hz)) {
        return -2;
    }
    if (acm8852_get_i2s_data_format(cfg, &i2s_data_format1, &i2s_data_format1_mask) != 0) {
        return -2;
    }

    if (try_all_i2c_addrs) {
        bool found = false;

        for (size_t i = 0; i < (sizeof(acm8852_addrs) / sizeof(acm8852_addrs[0])); i++) {
            dev->i2c_addr = acm8852_addrs[i];
            if (acm8852_write_init_sequence(dev) == 0) {
                printf("acm8852 init succeeded at i2c addr 0x%02x\r\n", dev->i2c_addr);
                found = true;
                break;
            }
        }

        if (!found) {
            dev->i2c_addr = 0U;
            printf("acm8852_write_init_sequence failed\r\n");
            return -1;
        }
    } else {
        if (acm8852_write_init_sequence(dev) != 0) {
            printf("acm8852_write_init_sequence failed\r\n");
            return -1;
        }
    }
    if (acm8852_config_i2s(dev, i2s_data_format1, i2s_data_format1_mask) != 0) {
        return -1;
    }
    g_acm8852_cfg = *cfg;
    dev->priv = &g_acm8852_cfg;

    if (!cfg->enable_dac) {
        ret = acm8852_set_output_state(dev, ACM8852_STATE_HIZ, true);
    } else {
        ret = acm8852_set_output_state(dev, ACM8852_STATE_PLAY, false);
    }
    if (ret != 0) {
        return ret;
    }

    acm8852_read_all_regs(dev);
    return 0;
}

static int audio_codec_acm8852_set_mute(audio_codec_dev_t *dev, bool mute)
{
    if (dev == NULL || dev->i2c == NULL) {
        return -1;
    }

    return acm8852_set_output_state(dev, ACM8852_STATE_PLAY, mute);
}

static int audio_codec_acm8852_set_volume(audio_codec_dev_t *dev, int volume_percent)
{
    uint8_t regv;
    int ret = 0;

    if (dev == NULL || dev->i2c == NULL) {
        return -1;
    }

    if (volume_percent < 0) {
        volume_percent = 0;
    } else if (volume_percent > 100) {
        volume_percent = 100;
    }

    regv = (uint8_t)((volume_percent * ACM8852_VOL_0DB + 50) / 100);

    ret |= acm8852_select_page(dev->i2c, dev->i2c_addr, 0x00);
    ret |= acm8852_write_reg(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_TARGET_VOL_CH1, regv);
    ret |= acm8852_write_reg(dev->i2c, dev->i2c_addr, ACM8852_REG_DIG_TARGET_VOL_CH2, regv);
    return (ret == 0) ? 0 : -1;
}

