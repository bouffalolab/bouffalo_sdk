#define TEST_MAX_DATA 4097U
static mbedtls_gcm_context ctx;
static uint8_t key[32], iv[16], aad[31], plain[TEST_MAX_DATA];
static uint8_t ciphertext[TEST_MAX_DATA], out[TEST_MAX_DATA], scratch[TEST_MAX_DATA], tag[16];

static int check_ciphertext(const vector_t *v, const uint8_t *data)
{
    uint8_t digest[32];
    int ret = mbedtls_sha256(data, v->size, digest, 0);
    return ret ? ret : memcmp(digest, v->digest, sizeof(digest));
}

static int setup_vector(const vector_t *v)
{
    for (unsigned i = 0; i < v->keylen; ++i) key[i] = (uint8_t)(i * 11U + v->keylen);
    for (unsigned i = 0; i < v->ivlen; ++i) iv[i] = (uint8_t)(i * 13U + v->index * 3U + v->keylen);
    for (unsigned i = 0; i < v->aadlen; ++i) aad[i] = (uint8_t)(i * 17U + v->index * 7U + v->keylen);
    for (unsigned i = 0; i < v->size; ++i) plain[i] = (uint8_t)(i * 7U + v->index * 5U + v->keylen);
    mbedtls_gcm_init(&ctx);
    return mbedtls_gcm_setkey(&ctx, MBEDTLS_CIPHER_ID_AES, key, v->keylen * 8U);
}

static int stream_run(const vector_t *v, int mode, int inplace)
{
    static const size_t chunks[] = { 1, 15, 16, 17, 63, 64, 65, 255, 256, 257 };
    size_t off = 0, outlen, final_len;
    int ret = mbedtls_gcm_starts(&ctx, mode, iv, v->ivlen);
    if (ret == 0) ret = mbedtls_gcm_update_ad(&ctx, aad, v->aadlen);
    memcpy(scratch, mode == MBEDTLS_GCM_ENCRYPT ? plain : ciphertext, v->size);
    for (unsigned i = 0; ret == 0 && off < v->size; ++i) {
        size_t len = chunks[i % (sizeof(chunks) / sizeof(chunks[0]))];
        if (len > v->size - off) len = v->size - off;
        ret = mbedtls_gcm_update(&ctx, scratch + off, len,
                                 (inplace ? scratch : out) + off, len, &outlen);
        if (ret == 0 && outlen != len) ret = -99;
        off += len;
    }
    if (ret == 0) ret = mbedtls_gcm_finish(&ctx, NULL, 0, &final_len, tag, sizeof(tag));
    if (ret != 0) return ret;
    if (memcmp(tag, v->tag, sizeof(tag))) return -98;
    if (mode == MBEDTLS_GCM_ENCRYPT)
        return check_ciphertext(v, inplace ? scratch : out);
    return memcmp(inplace ? scratch : out, plain, v->size);
}

