typedef struct {
    mbedtls_gcm_context ctx;
    unsigned id;
    int result;
} concurrent_case_t;
static concurrent_case_t concurrent_cases[2];
static SemaphoreHandle_t concurrent_done;

static void concurrent_worker(void *arg)
{
    concurrent_case_t *test = arg;
    uint8_t key_local[16], iv_local[12], input[64], output[80];
    memset(key_local, test->id + 1, sizeof(key_local));
    memset(iv_local, test->id + 1, sizeof(iv_local));
    for (unsigned i = 0; i < sizeof(input); ++i) input[i] = (uint8_t)(i + test->id + 1);
    test->result = 0;
    for (unsigned iteration = 0; iteration < 32 && test->result == 0; ++iteration) {
        size_t output_len = 0;
        mbedtls_gcm_init(&test->ctx);
        int ret = mbedtls_gcm_setkey(&test->ctx, MBEDTLS_CIPHER_ID_AES, key_local, 128);
        if (!ret) ret = mbedtls_gcm_starts(&test->ctx, MBEDTLS_GCM_ENCRYPT, iv_local, sizeof(iv_local));
        for (unsigned offset = 0; !ret && offset < sizeof(input); offset += 16) {
            ret = mbedtls_gcm_update(&test->ctx, input + offset, 16, output + offset, 16, &output_len);
            if (!ret && output_len != 16) ret = -1;
            vTaskDelay(pdMS_TO_TICKS(1));
        }
        if (!ret) ret = mbedtls_gcm_finish(&test->ctx, NULL, 0, &output_len, output + 64, 16);
        if (!ret && (output_len != 0 || memcmp(output, concurrent_expected[test->id], sizeof(output)))) ret = -1;
        mbedtls_gcm_free(&test->ctx);
        test->result = ret;
        vTaskDelay(pdMS_TO_TICKS(1));
    }
    xSemaphoreGive(concurrent_done);
    vTaskDelete(NULL);
}

static int cli_gcm_concurrent(int argc, char **argv)
{
    unsigned started = 0;
    (void)argc; (void)argv;
    if (concurrent_done) return -1;
    concurrent_done = xSemaphoreCreateCounting(2, 0);
    if (!concurrent_done) return -1;
    for (unsigned i = 0; i < 2; ++i) {
        concurrent_cases[i].id = i;
        if (xTaskCreate(concurrent_worker, "gcm_concurrent", 1024, &concurrent_cases[i],
                        tskIDLE_PRIORITY + 2, NULL) != pdPASS) break;
        ++started;
    }
    for (unsigned i = 0; i < started; ++i) {
        if (xSemaphoreTake(concurrent_done, pdMS_TO_TICKS(30000)) != pdTRUE) {
            printf("GCM_CONCURRENT FAIL timeout\r\n");
            return -1; /* Keep the semaphore alive for any worker still running. */
        }
    }
    vSemaphoreDelete(concurrent_done);
    concurrent_done = NULL;
    if (started != 2 || concurrent_cases[0].result || concurrent_cases[1].result) {
        printf("GCM_CONCURRENT FAIL started=%u result=%d/%d\r\n", started,
               concurrent_cases[0].result, concurrent_cases[1].result);
        return -1;
    }
    printf("GCM_CONCURRENT PASS contexts=2 rounds=32 streaming=rekey\r\n");
    return 0;
}
