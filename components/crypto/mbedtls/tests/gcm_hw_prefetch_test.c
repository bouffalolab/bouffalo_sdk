static int cli_gcm_bench(int argc, char **argv)
{
    uint32_t min_us = UINT32_MAX, max_us = 0;
    uint64_t total_us = 0;
    int ret;
    (void)argc; (void)argv;
    memset(key, 0, 16); memset(iv, 0, 12); memset(aad, 0, 13); memset(plain, 0, 1196);
    mbedtls_gcm_init(&ctx);
    ret = mbedtls_gcm_setkey(&ctx, MBEDTLS_CIPHER_ID_AES, key, 128);
    for (unsigned run = 0; ret == 0 && run < 20; ++run) {
        size_t left = 65536;
        uint32_t start = (uint32_t)bflb_mtimer_get_time_us();
        for (unsigned part = 0; ret == 0 && left; ++part) {
            size_t payload = left > 1152 ? 1152 : left;
            iv[8] = run; iv[9] = part; iv[10] = part >> 8; iv[11]++;
            ret = mbedtls_gcm_crypt_and_tag(&ctx, MBEDTLS_GCM_ENCRYPT,
                payload + 44, iv, 12, aad, 13, plain, out, 16, tag);
            left -= payload;
        }
        uint32_t elapsed = (uint32_t)bflb_mtimer_get_time_us() - start;
        if (elapsed < min_us) min_us = elapsed;
        if (elapsed > max_us) max_us = elapsed;
        total_us += elapsed;
    }
    if (ret == 0) printf("GCM_HW_BENCH frame=65536 chunks=57 rounds=20 avg_us=%lu min_us=%lu max_us=%lu\r\n",
        (unsigned long)(total_us / 20), (unsigned long)min_us, (unsigned long)max_us);
    else printf("GCM_HW_BENCH FAIL=%d\r\n", ret);
    mbedtls_gcm_free(&ctx);
    return ret;
}
